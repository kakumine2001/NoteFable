// 原生 Android 多语言界面文案（mobile/android/app/src/main/res/values-*/*.xml）。
// 默认英文资源（res/values/strings*.xml）与网页字典（src/lib/i18n/messages/*.ts）同源；
// 新增的 13 种语言（ko / es / fr / de / pt-BR / it / id / vi / th / hi / ar / tr / ru）直接从网页字典生成，
// 保证键集合、占位符（%1$s / %1$d / %%）与 Android XML 转义规则完全一致。
// 生成：npx tsx scripts/gen-native-strings.ts；src/lib/native-language.test.ts 检查资源是否完整且未过期。
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import type { Locale } from "../src/lib/i18n/locale";
import { messagesFor } from "../src/lib/i18n/messages";

const root = path.resolve(import.meta.dirname, "..");
export const NATIVE_RES_DIR = path.join(root, "mobile", "android", "app", "src", "main", "res");
export const NATIVE_DEFAULT_VALUES_DIR = path.join(NATIVE_RES_DIR, "values");

// Android 资源目录限定符：印尼语在 Android 资源表中使用传统代码 values-in，巴西葡萄牙语使用 values-pt-rBR。
export const NATIVE_LOCALE_RES_DIRS: Record<Locale, string> = {
  en: "values",
  zh: "values-zh",
  "zh-Hant": "values-b+zh+Hant",
  ja: "values-ja",
  ko: "values-ko",
  es: "values-es",
  fr: "values-fr",
  de: "values-de",
  "pt-BR": "values-pt-rBR",
  it: "values-it",
  id: "values-in",
  vi: "values-vi",
  th: "values-th",
  hi: "values-hi",
  ar: "values-ar",
  tr: "values-tr",
  ru: "values-ru",
};

export const GENERATED_NATIVE_LOCALES = [
  "ko", "es", "fr", "de", "pt-BR", "it",
  "id", "vi", "th", "hi", "ar", "tr", "ru",
] as const satisfies readonly Exclude<Locale, "en" | "zh" | "zh-Hant" | "ja">[];

export type GeneratedNativeLocale = (typeof GENERATED_NATIVE_LOCALES)[number];

const HEADER = "<!-- Generated by scripts/gen-native-strings.ts from res/values and src/lib/i18n/messages. Do not edit by hand. -->";

// 同一英文句型在网页里拆成两个占位符名字的情况，显式指定对应的网页键。
const EXPLICIT_WEB_KEYS: Record<string, string> = {
  sb_actions_for_title: "Actions for {title}",
  sb_actions_for_name: "Actions for {name}",
};

export function unescapeAndroidString(raw: string): { text: string; quoted: boolean; specs: string[] } {
  let s = raw;
  let quoted = false;
  if (s.startsWith('"') && s.endsWith('"') && s.length >= 2) {
    s = s.slice(1, -1);
    quoted = true;
  }
  s = s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/\\(['"?@\\n])/g, (_, c: string) => (c === "n" ? "\n" : c));
  const specs = [...s.matchAll(/%\d+\$[sd]/g)].map((m) => m[0]);
  if (specs.length > 0) s = s.replace(/%%/g, "%");
  return { text: s, quoted, specs };
}

export function escapeAndroidString(value: string, forceQuote: boolean): string {
  const needsQuote = forceQuote || /^\s|\s$/.test(value);
  const xmlEscaped = value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
  if (needsQuote) {
    const inner = xmlEscaped.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
    return `"${inner}"`;
  }
  return xmlEscaped
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/^([@?])/, "\\$1")
    .replace(/\n/g, "\\n");
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

type ResolvedEntry =
  | { kind: "ui_locale"; name: string }
  | { kind: "literal"; name: string; value: string }
  | { kind: "translated"; name: string; webKey: string; webSlots: string[]; specs: string[]; quoted: boolean };

function resolveDefaultXmlEntries(xml: string, referenceKeys: string[], fileName: string): ResolvedEntry[] {
  const entries: ResolvedEntry[] = [];
  for (const match of xml.matchAll(/<string\s+name="([^"]+)"([^>]*)>([\s\S]*?)<\/string>/g)) {
    const [, name, attrs, raw] = match;
    if (/\btranslatable\s*=\s*"false"/.test(attrs)) continue;
    if (name === "ui_locale") {
      entries.push({ kind: "ui_locale", name });
      continue;
    }
    if (raw === "NoteFable") {
      entries.push({ kind: "literal", name, value: "NoteFable" });
      continue;
    }
    const { text, quoted, specs } = unescapeAndroidString(raw);
    let webKey = EXPLICIT_WEB_KEYS[name];
    if (!webKey) {
      if (specs.length === 0) {
        const normalized = text.replace(/’/g, "'");
        const candidates = referenceKeys.filter((k) => k === text || k.replace(/’/g, "'") === normalized);
        if (candidates.length !== 1) {
          throw new Error(`Cannot uniquely resolve Web key for ${fileName}:${name} (${JSON.stringify(text)}): [${candidates.join(", ")}]`);
        }
        webKey = candidates[0];
      } else {
        const parts = text.split(/%\d+\$[sd]/);
        const pattern = "^" + parts.map((p) => escapeRegExp(p).replace(/['’]/g, "['’]")).join("\\{(\\w+)\\}") + "$";
        const regex = new RegExp(pattern);
        const candidates = referenceKeys.filter((k) => regex.test(k));
        if (candidates.length !== 1) {
          throw new Error(`Cannot uniquely resolve templated Web key for ${fileName}:${name} (${JSON.stringify(text)}): [${candidates.join(", ")}]`);
        }
        webKey = candidates[0];
      }
    }
    const webSlots = [...webKey.matchAll(/\{\w+\}/g)].map((m) => m[0]);
    if (webSlots.length !== specs.length) {
      throw new Error(`Slot count mismatch for ${fileName}:${name}: webKey=${webKey} vs android=${text}`);
    }
    entries.push({ kind: "translated", name, webKey, webSlots, specs, quoted });
  }
  return entries;
}

function formatTranslatedAndroidValue(
  translated: string,
  webSlots: string[],
  specs: string[],
  quoted: boolean,
): string {
  let text = translated;
  if (specs.length > 0) {
    text = text.replace(/%/g, "%%");
    const counts = new Map<string, number>();
    for (const slot of webSlots) counts.set(slot, (counts.get(slot) ?? 0) + 1);
    const hasDuplicateSlot = [...counts.values()].some((count) => count > 1);
    if (hasDuplicateSlot) {
      // 同一占位符出现多次（如 {size} × {size} → %1$d × %2$d）：按出现顺序依次替换。
      const queues = new Map<string, string[]>();
      webSlots.forEach((slot, idx) => {
        const list = queues.get(slot) ?? [];
        list.push(specs[idx]);
        queues.set(slot, list);
      });
      text = text.replace(/\{\w+\}/g, (slot) => {
        const list = queues.get(slot);
        const next = list?.shift();
        if (!next) throw new Error(`Unexpected placeholder ${slot} in "${translated}"`);
        return next;
      });
    } else {
      const specBySlot = new Map(webSlots.map((slot, idx) => [slot, specs[idx]]));
      text = text.replace(/\{\w+\}/g, (slot) => {
        const spec = specBySlot.get(slot);
        if (!spec) throw new Error(`Unexpected placeholder ${slot} in "${translated}"`);
        return spec;
      });
    }
  }
  return escapeAndroidString(text, quoted);
}

export function defaultStringXmlFileNames(): string[] {
  return readdirSync(NATIVE_DEFAULT_VALUES_DIR)
    .filter((name) => name.startsWith("strings") && name.endsWith(".xml"))
    .sort();
}

export function nativeLocaleStringFiles(locale: GeneratedNativeLocale): Map<string, string> {
  const referenceKeys = Object.keys(messagesFor("ja"));
  const dictionary = messagesFor(locale);
  const files = defaultStringXmlFileNames();
  const out = new Map<string, string>();

  for (const fileName of files) {
    const defaultXml = readFileSync(path.join(NATIVE_DEFAULT_VALUES_DIR, fileName), "utf8");
    const entries = resolveDefaultXmlEntries(defaultXml, referenceKeys, fileName);
    const lines = [
      '<?xml version="1.0" encoding="utf-8"?>',
      HEADER,
      "<resources>",
    ];
    for (const entry of entries) {
      if (entry.kind === "ui_locale") {
        lines.push(`    <string name="${entry.name}">${locale}</string>`);
      } else if (entry.kind === "literal") {
        lines.push(`    <string name="${entry.name}">${entry.value}</string>`);
      } else {
        const translated = dictionary[entry.webKey];
        if (!translated) {
          throw new Error(`Missing ${locale} translation for ${fileName}:${entry.name} (${entry.webKey})`);
        }
        const formatted = formatTranslatedAndroidValue(translated, entry.webSlots, entry.specs, entry.quoted);
        lines.push(`    <string name="${entry.name}">${formatted}</string>`);
      }
    }
    lines.push("</resources>", "");
    out.set(fileName, lines.join("\n"));
  }
  return out;
}
