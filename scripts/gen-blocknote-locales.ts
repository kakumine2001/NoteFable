// Generate standalone per-locale BlockNote dictionary modules from @blocknote/core's
// upstream source files so client bundlers split each language into its own ~2 kB chunk
// instead of pulling the shared @blocknote/core/locales barrel (~35 kB gz).
// Run after upgrading @blocknote/core:
//   npx tsx scripts/gen-blocknote-locales.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

export const UPSTREAM_BLOCKNOTE_LOCALES = [
  { file: "zh.ts", upstream: "zh.ts", exportName: "zh" },
  { file: "zh-hant.ts", upstream: "zh-tw.ts", exportName: "zhTW" },
  { file: "ja.ts", upstream: "ja.ts", exportName: "ja" },
  { file: "ko.ts", upstream: "ko.ts", exportName: "ko" },
  { file: "es.ts", upstream: "es.ts", exportName: "es" },
  { file: "fr.ts", upstream: "fr.ts", exportName: "fr" },
  { file: "de.ts", upstream: "de.ts", exportName: "de" },
  { file: "pt-br.ts", upstream: "pt.ts", exportName: "pt" },
  { file: "it.ts", upstream: "it.ts", exportName: "it" },
  { file: "vi.ts", upstream: "vi.ts", exportName: "vi" },
  { file: "ar.ts", upstream: "ar.ts", exportName: "ar" },
  { file: "ru.ts", upstream: "ru.ts", exportName: "ru" },
] as const;

const root = path.resolve(import.meta.dirname, "..");
export const BLOCKNOTE_LOCALES_DIR = path.join(root, "src/lib/i18n/blocknote-locales");
const upstreamDir = path.join(root, "node_modules/@blocknote/core/src/i18n/locales");

export function renderUpstreamBlockNoteLocale(upstreamFile: string, exportName: string): string {
  const raw = readFileSync(path.join(upstreamDir, upstreamFile), "utf8").replace(/\r\n/g, "\n");
  const body = raw
    .replace(/^import\s+(?:type\s+)?\{\s*Dictionary\s*\}\s+from\s+"\.\.\/dictionary\.js";\n+/, "")
    .replace(new RegExp(`export const ${exportName}:\\s*Dictionary\\s*=`), "export const dictionary: Dictionary =");
  if (!body.includes("export const dictionary: Dictionary =")) {
    throw new Error(`Unexpected format in upstream BlockNote locale ${upstreamFile}`);
  }
  return `// Generated by scripts/gen-blocknote-locales.ts from @blocknote/core (${upstreamFile}). Do not edit by hand.\nimport type { Dictionary } from "@blocknote/core";\n\n${body}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(BLOCKNOTE_LOCALES_DIR, { recursive: true });
  for (const entry of UPSTREAM_BLOCKNOTE_LOCALES) {
    const out = path.join(BLOCKNOTE_LOCALES_DIR, entry.file);
    writeFileSync(out, renderUpstreamBlockNoteLocale(entry.upstream, entry.exportName));
  }
  console.log(`wrote ${UPSTREAM_BLOCKNOTE_LOCALES.length} upstream BlockNote locale modules to ${BLOCKNOTE_LOCALES_DIR}`);
}
