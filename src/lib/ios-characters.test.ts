import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { IOS_CHARACTERS_SWIFT, renderIosCharactersSwift } from "../../scripts/ios-characters";
import { CHARACTER_DEFINITIONS, CHARACTER_IDS, DEFAULT_CHARACTER_ID } from "./characters";

const count = (text: string, needle: string) => text.split(needle).length - 1;

describe("iOS characters data", () => {
  it("is up to date (regenerate with npx tsx scripts/gen-ios-characters.ts)", () => {
    const swiftPath = path.resolve(import.meta.dirname, "../..", IOS_CHARACTERS_SWIFT);
    expect(readFileSync(swiftPath, "utf8").replace(/\r\n/g, "\n")).toBe(renderIosCharactersSwift());
  });

  it("carries every character, layer, eye and view box from src/lib/characters.ts", () => {
    const swift = renderIosCharactersSwift();
    expect(swift.startsWith("// Generated by scripts/gen-ios-characters.ts")).toBe(true);

    // 枚举 case 的顺序就是 CHARACTER_IDS 的顺序（CaseIterable 靠它）。
    expect([...swift.matchAll(/^ {4}case (\w+)$/gm)].map((match) => match[1])).toEqual([...CHARACTER_IDS]);
    expect(swift).toContain(`static let \`default\`: CharacterId = .${DEFAULT_CHARACTER_ID}`);

    const layers = CHARACTER_DEFINITIONS.flatMap((c) => [...c.backAccentPaths, ...c.bodyPaths, ...c.frontAccentPaths]);
    expect(count(swift, "CharacterPath(d: ")).toBe(layers.length);
    for (const layer of layers) expect(swift).toContain(`CharacterPath(d: "${layer.d}"`);
    expect(count(swift, "CharacterEye.Capsule(") + count(swift, "CharacterEye.Polygon(")).toBe(
      CHARACTER_DEFINITIONS.reduce((total, c) => total + c.eyes.length, 0),
    );

    for (const c of CHARACTER_DEFINITIONS) {
      expect(swift).toContain(`case .${c.id}: return "${c.name}"`);
      expect(swift).toContain(`case .${c.id}: return ${Boolean(c.isDefault)}`);
      expect(swift).toContain(`.${c.id}: ${c.id}Spec,`);
      expect(swift).toContain(`floatDurationMs: ${c.motion.floatDurationMs},`);
    }

    // #RRGGBB -> 0xFFRRGGBB；没有填充 / 描边的是 nil。
    expect(swift).toContain("fillArgb: 0xFFDCD2BE, strokeArgb: nil, strokeWidth: 0, strokeCap: .butt, strokeJoin: .miter, evenOdd: false)");
    expect(swift).toContain("fillArgb: nil, strokeArgb: 0xFF0F172A, strokeWidth: 8.5, strokeCap: .butt, strokeJoin: .round, evenOdd: false)");
    expect(swift).toContain("static let iconViewBox = CharacterViewBox(x: 16, y: 14, width: 208, height: 212)");
    expect(swift).toContain("static let heroViewBox = CharacterViewBox(x: 12, y: 10, width: 216, height: 229.5)");
  });
});
